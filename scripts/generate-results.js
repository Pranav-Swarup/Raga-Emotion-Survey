// Run with: node scripts/generate-results.js
//
// Pulls the current data from the results_public view (see ../results-view.sql)
// and writes it into ../results-data.js as a plain JS array — the results
// page (index.html -> screen-results) reads from that static file, not a live
// API call. Re-run this after a fresh batch of responses comes in, then
// commit + push results-data.js to update the highlight page.

const fs = require("fs");
const path = require("path");

const configPath = path.join(__dirname, "..", "config.js");
const configSrc = fs.readFileSync(configPath, "utf8");
const urlMatch = configSrc.match(/SUPABASE_URL\s*=\s*"([^"]+)"/);
const keyMatch = configSrc.match(/SUPABASE_ANON_KEY\s*=\s*"([^"]+)"/);
if (!urlMatch || !keyMatch) {
  console.error("Couldn't find SUPABASE_URL / SUPABASE_ANON_KEY in config.js");
  process.exit(1);
}
const SUPABASE_URL = urlMatch[1];
const SUPABASE_ANON_KEY = keyMatch[1];

async function main() {
  const res = await fetch(`${SUPABASE_URL}/rest/v1/results_public?select=*`, {
    headers: {
      apikey: SUPABASE_ANON_KEY,
      Authorization: `Bearer ${SUPABASE_ANON_KEY}`,
    },
  });
  if (!res.ok) {
    console.error("Fetch failed:", res.status, await res.text());
    process.exit(1);
  }
  const rows = await res.json();

  const outPath = path.join(__dirname, "..", "results-data.js");
  const banner =
    "// Static snapshot of results_public, generated by scripts/generate-results.js.\n" +
    `// Generated at: ${new Date().toISOString()}\n` +
    "// Do not hand-edit — re-run the script and commit the new file instead.\n";
  const body = `const RESULTS_DATA = ${JSON.stringify(rows, null, 2)};\n`;
  fs.writeFileSync(outPath, banner + body);

  const byRaga = {};
  rows.forEach((r) => { byRaga[r.raga] = (byRaga[r.raga] || 0) + 1; });
  console.log(`Wrote ${rows.length} rows to results-data.js`);
  console.log(byRaga);
}

main().catch((e) => { console.error(e); process.exit(1); });
